"""Rendering inferred configuration as the Python a developer would have written.

Inference is only trustworthy if you can see it. This turns the engine's output into a
real ``panel.py`` the developer then owns — the difference between a helpful default
and an opaque black box. Once written out, the file is ordinary code: readable in a
diff, editable, and no longer subject to inference changing under it on upgrade.
"""

from __future__ import annotations

from django.apps import apps as django_apps
from django.db.models import Model

from vantage.inference import infer_all

__all__ = ["render_panel_class", "render_panel_module"]

HEADER = '''"""Vantage panel configuration for the {app} app.

Generated by ``manage.py vantage_scaffold {app}``. These values are what
Vantage would have inferred; they are written out so you can see and change
them. Deleting an attribute returns it to inference. Deleting the whole file
is also fine — the models stay registered.
"""

from vantage import ModelPanel, register

{imports}


'''

#: Keep generated lines inside 88 columns once the indent and attribute name are
#: added, so the output passes a formatter without being reflowed.
INLINE_BUDGET = 60


def _format_list(values: list[str], indent: str = "    ") -> str:
    """One entry per line once the list would otherwise run long."""
    inline = "[" + ", ".join(f'"{v}"' for v in values) + "]"
    if len(inline) <= INLINE_BUDGET:
        return inline
    body = "".join(f'\n{indent}    "{v}",' for v in values)
    return f"[{body}\n{indent}]"


def render_panel_class(model: type[Model]) -> str:
    """Render one ``@register``-decorated panel class for ``model``."""
    inferred = infer_all(model)
    name = f"{model.__name__}Panel"

    lines = [
        f"@register({model.__name__})",
        f"class {name}(ModelPanel):",
    ]

    for attr in ("list_display", "list_link", "list_filter", "list_search", "ordering"):
        value = inferred[attr]
        if not value:
            continue
        rendered = f'"{value}"' if isinstance(value, str) else _format_list(value)
        lines.append(f"    {attr} = {rendered}")

    if len(lines) == 2:  # nothing worth writing
        lines.append("    pass")

    return "\n".join(lines)


def render_panel_module(app_label: str, models: list[type[Model]] | None = None) -> str:
    """Render a complete ``panel.py`` for one app."""
    app_config = django_apps.get_app_config(app_label)
    if models is None:
        models = sorted(app_config.get_models(), key=lambda m: m.__name__)

    if not models:
        return HEADER.format(app=app_label, imports="") + "# No models in this app.\n"

    module = models[0].__module__
    names = ", ".join(m.__name__ for m in models)
    imports = f"from {module} import {names}"

    body = "\n\n\n".join(render_panel_class(m) for m in models)
    return HEADER.format(app=app_label, imports=imports) + body + "\n"
